// Builds renderer/icons.js from Lucide (ISC licence) so the app ships only
// the icons it uses. Run: node tools/gen-icons.js
const fs = require('fs');
const path = require('path');
const NAMES = {
  add: 'plus', resume: 'play', stop: 'square', stopAll: 'circle-stop', pause: 'pause', remove: 'trash-2', removeDone: 'list-checks',
  options: 'settings', scheduler: 'alarm-clock', startQueue: 'list-start', stopQueue: 'list-x', grabber: 'scan-search', batch: 'layers',
  limiter: 'gauge', search: 'search', folder: 'folder', folderOpen: 'folder-open', file: 'file', chevronRight: 'chevron-right',
  chevronDown: 'chevron-down', close: 'x', check: 'check', up: 'arrow-up', down: 'arrow-down', download: 'download', info: 'info',
  alert: 'circle-alert', moon: 'moon', sun: 'sun', globe: 'globe', link: 'link', copy: 'copy', external: 'external-link', refresh: 'refresh-cw',
  compressed: 'archive', documents: 'file-text', music: 'music', programs: 'app-window', video: 'film', general: 'file', all: 'folder-down',
  unfinished: 'hourglass', finished: 'circle-check', queues: 'list-ordered', queue: 'list-video', projects: 'scan-search', keyboard: 'keyboard',
  sound: 'volume-2', shield: 'shield-check', network: 'network', key: 'key-round', plug: 'plug', save: 'save', types: 'file-type', retry: 'rotate-ccw',
  folderPlus: 'folder-plus', edit: 'pencil', calendar: 'calendar-clock', power: 'power', exit: 'log-out', play: 'play', minus: 'minus',
  dots: 'ellipsis', sidebar: 'panel-left', tray: 'app-window-mac', category: 'tag', help: 'circle-help', star: 'sparkles', bolt: 'zap'
};
const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const out = {};
for (const [key, name] of Object.entries(NAMES)) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  out[key] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}
const js = `// Generated by tools/gen-icons.js from Lucide (https://lucide.dev), ISC licence.\nexport const ICONS = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'renderer', 'icons.js'), js);
console.log(`${Object.keys(out).length} icons`);
